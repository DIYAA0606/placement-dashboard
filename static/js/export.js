"use strict";

function exportProgressReport() {

  const { jsPDF } = window.jspdf;
  if (!jsPDF) {
    toast("PDF library not loaded", "error");
    return;
  }

  const doc = new jsPDF();
  const profile = typeof getProfile === "function" ? getProfile() : {};

  let y = 20;
  const LINE = 8;
  const SECTION_GAP = 14;

  // ── Header ──────────────────────────────────────────
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text("PlacePrep — Progress Report", 20, y);
  y += LINE + 2;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(120);
  doc.text(`Generated: ${new Date().toLocaleString()}`, 20, y);
  if (profile.name) {
    doc.text(`Student: ${profile.name}`, 120, y);
  }
  y += SECTION_GAP;
  doc.setTextColor(0);

  // ── Readiness Score ──────────────────────────────────
  const resumeHistory = typeof getAnalysisHistory === "function" ? getAnalysisHistory() : [];
  const resumeScore   = resumeHistory.length ? resumeHistory[0].percentage : 0;
  const dsaData       = typeof getDSAProgress === "function" ? getDSAProgress() : { solved: 0, total: 0, percentage: 0 };
  const plannerData   = typeof getPlannerStats === "function" ? getPlannerStats() : { completed: 0, total: 0, percentage: 0 };
  const streak        = typeof calculateStreak === "function" ? calculateStreak() : 0;

  const readiness = (resumeScore || dsaData.percentage || plannerData.percentage)
    ? Math.round(resumeScore * 0.4 + dsaData.percentage * 0.35 + plannerData.percentage * 0.25)
    : 0;

  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text("Placement Readiness", 20, y);
  y += LINE;

  doc.setFontSize(11);
  doc.setFont("helvetica", "normal");
  doc.text(`Overall Score:   ${readiness || "—"}${readiness ? "%" : ""}`, 20, y); y += LINE;
  doc.text(`Resume ATS:      ${resumeScore || "—"}${resumeScore ? "%" : ""}   (weight 40%)`, 20, y); y += LINE;
  doc.text(`DSA Progress:    ${dsaData.percentage}%   (weight 35%)`, 20, y); y += LINE;
  doc.text(`Tasks Done:      ${plannerData.percentage}%   (weight 25%)`, 20, y); y += LINE;
  doc.text(`Study Streak:    ${streak} day${streak !== 1 ? "s" : ""}`, 20, y);
  y += SECTION_GAP;

  // ── DSA Breakdown ────────────────────────────────────
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text("DSA Progress", 20, y);
  y += LINE;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Solved: ${dsaData.solved} / ${dsaData.total} problems (${dsaData.percentage}%)`, 20, y);
  y += LINE;

 if (typeof getDSAState === "function") {
  const topics = getDSAState();
  topics.forEach(topic => {
    const solved = topic.problems.filter(p => p.completed).length;
    const total  = topic.problems.length;
    const pct    = total ? Math.round((solved / total) * 100) : 0;

    doc.setFont("helvetica", "bold");
    doc.text(`${topic.title} — ${solved}/${total} (${pct}%)`, 20, y);
    y += LINE;
    if (y > 270) { doc.addPage(); y = 20; }

    doc.setFont("helvetica", "normal");
    topic.problems.forEach(p => {
      const status = p.completed ? "[x]" : "[ ]";
      doc.text(`    ${status} ${p.name}`, 20, y);
      y += LINE - 1;
      if (y > 270) { doc.addPage(); y = 20; }
    });

    y += 4;
  });
}

  // ── Planner Summary ──────────────────────────────────
  doc.setFontSize(13);
  doc.setFont("helvetica", "bold");
  doc.text("Study Planner", 20, y);
  y += LINE;

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(`Completed: ${plannerData.completed} / ${plannerData.total} active tasks`, 20, y);
  y += SECTION_GAP;

  // ── Footer ───────────────────────────────────────────
  doc.setFontSize(9);
  doc.setTextColor(150);
  doc.text("Generated by PlacePrep — Placement Preparation OS", 20, 285);

  doc.save(`placeprep-report-${new Date().toISOString().split("T")[0]}.pdf`);
  toast("Progress report downloaded", "success");

  if (typeof logEvent === "function") {
    logEvent("resume", `Progress report exported`);
  }
}
document.addEventListener("DOMContentLoaded", () => {
  getEl("exportProgressBtn")?.addEventListener("click", exportProgressReport);
});